package com.gios.brightledger.demo

import com.gios.brightledger.data.AccountEntity
import com.gios.brightledger.data.TransactionWithAccount

/**
 * A complete synthetic ledger, for screenshots.
 *
 * **This is temporary and is scheduled for deletion.** It exists so the app can be
 * photographed without photographing someone's bank account, and the whole of it lives in
 * this one file plus a preference and three call sites, so removing it is a delete rather
 * than an unpick.
 *
 * It **replaces** the dataset rather than obscuring it. An earlier sketch transformed real
 * rows — renaming merchants, scaling amounts — and that is the wrong shape twice over. It
 * leaks the structure of the real data (how many accounts, how often you shop, what your
 * balance roughly is), and it produces a bad screenshot whenever reality is uninteresting:
 * nothing spent today, one account, a quiet week. Generating from nothing gives a screen
 * that always looks like the app working, and cannot leak what it never read.
 *
 * Everything downstream then works unchanged, which is the point of putting it here rather
 * than in the composables. The totals header, the recurring detector and the transaction
 * detail page all read these rows through their normal paths, so what you photograph is the
 * real app with different numbers in it, not a mock-up that will drift from the app.
 *
 * Deterministic on purpose. Dates are relative to now so "Today" and "Yesterday" are always
 * populated, but the merchants, amounts and ordering are fixed, so two screenshots taken an
 * hour apart are comparable and a rebuilt screenshot matches the one it replaces.
 */
object Demo {

    const val CONNECTION_ID = "demo"
    const val HOST = "bridge.simplefin.org"

    private const val DAY = 86_400L

    private fun now(): Long = System.currentTimeMillis() / 1000

    fun accounts(): List<AccountEntity> = listOf(
        account("checking", "Everyday Checking (4021)", 248_137L, 244_500L),
        account("card", "Rewards Card (8890)", -87_412L, null),
        account("savings", "Savings (1173)", 1_240_600L, null),
    )

    private fun account(
        id: String,
        name: String,
        balanceCents: Long,
        availableCents: Long?,
    ) = AccountEntity(
        id = AccountEntity.key(CONNECTION_ID, id),
        connectionId = CONNECTION_ID,
        remoteId = id,
        name = name,
        connId = "demo-conn",
        connName = "Demo Bank",
        currency = "USD",
        balanceCents = balanceCents,
        availableCents = availableCents,
        // Recent, so the account rows do not read as stale next to a fresh sync line.
        balanceDate = now() - 900,
        problem = null,
    )

    /**
     * Roughly six weeks of plausible spending.
     *
     * The monthly repeats are here three times each at a steady interval on purpose: the
     * Repeats screen is generated by the real detector from these rows, so the only way to
     * have it populate in a screenshot is to give it a pattern it genuinely recognises.
     */
    fun feed(): List<TransactionWithAccount> {
        val t = now()
        val rows = mutableListOf<TransactionWithAccount>()
        var seq = 0

        fun add(daysAgo: Long, hour: Long, cents: Long, description: String, card: Boolean = true) {
            seq++
            val at = t - daysAgo * DAY - hour * 3600
            rows += TransactionWithAccount(
                accountId = AccountEntity.key(CONNECTION_ID, if (card) "card" else "checking"),
                txnId = "demo-" + seq,
                at = at,
                posted = at,
                amountCents = cents,
                description = description,
                pending = false,
                accountName = if (card) "Rewards Card (8890)" else "Everyday Checking (4021)",
                currency = "USD",
            )
        }

        // Today, with one still pending — the pending count in the header is worth showing.
        seq++
        rows += TransactionWithAccount(
            accountId = AccountEntity.key(CONNECTION_ID, "card"),
            txnId = "demo-pending",
            at = t - 5_400,
            posted = 0,
            amountCents = -1_845,
            description = "SWEETGREEN",
            pending = true,
            accountName = "Rewards Card (8890)",
            currency = "USD",
        )
        add(0, 3, -420, "BLUE BOTTLE COFFEE")
        add(0, 7, -3_268, "TRADER JOES 545")

        add(1, 2, -1_204, "MTA VENDING MACHINE")
        add(1, 6, -6_450, "LUCALI")
        add(1, 9, -899, "NYT DIGITAL")

        add(2, 8, -2_237, "WHOLE FOODS BOWERY")

        add(3, 9, -4_800, "SHAPE HOUSE")
        add(4, 3, -812, "BODEGA DELI")
        add(5, 6, -12_400, "UNIQLO SOHO")
        add(6, 2, -505, "BLUE BOTTLE COFFEE")
        add(7, 4, -2_995, "APPLE STORE")
        add(8, 7, -1_780, "ROSS & DAUGHTERS")
        add(9, 5, -640, "BLUE BOTTLE COFFEE")
        add(12, 6, -2_140, "CVS 4021")
        add(14, 2, -1_950, "ANGELIKA FILM CENTER")
        add(15, 8, -3_410, "TRADER JOES 545")
        add(18, 4, -1_099, "AMAZON")
        add(26, 2, -710, "BLUE BOTTLE COFFEE")
        add(28, 7, -4_250, "SUNDAY IN BROOKLYN")
        add(33, 5, -2_890, "DUANE READE")

        // The repeats, at a genuine thirty-day cadence.
        //
        // The detector requires three occurrences and every gap to match the median, which
        // is what stops three coffees reading as a subscription. That means a monthly
        // charge needs sixty days of history before it can be recognised at all, so the
        // synthetic feed reaches back further than the part anyone will scroll to. Planting
        // them nineteen days apart, as the first version did, produced a Repeats screen that
        // confidently called everything biweekly.
        for (month in 0..2) {
            val shift = month * 30L
            add(2 + shift, 4, -1_599, "NETFLIX")
            add(5 + shift, 5, -1_099, "SPOTIFY USA")
            add(11 + shift, 3, -8_900, "CON EDISON", card = false)
            add(24 + shift, 6, -5_600, "VERIZON WIRELESS", card = false)
        }

        // Money in, so the sign handling is visible and the month has a credit in it.
        add(2, 11, 320_000, "ACME CORP PAYROLL", card = false)
        add(17, 11, 320_000, "ACME CORP PAYROLL", card = false)

        return rows.sortedWith(
            compareByDescending<TransactionWithAccount> { it.pending }.thenByDescending { it.at },
        )
    }

    /** One row, for the detail screen reached by tapping a demo transaction. */
    fun transaction(accountId: String, txnId: String): TransactionWithAccount? =
        feed().firstOrNull { it.accountId == accountId && it.txnId == txnId }

    /** A believable "synced a few minutes ago" rather than a real timestamp. */
    fun lastSync(): Long = now() - 214

    /** Stable but meaningless, so a screenshot of Settings shows no real host. */
    fun connectionLabel(): String = "Demo Bank"

    /** Whether an account key belongs to this synthetic set rather than a real server. */
    fun isDemoKey(key: String): Boolean = key.substringBefore('|', "") == CONNECTION_ID
}
